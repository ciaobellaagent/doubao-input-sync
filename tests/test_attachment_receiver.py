def item(body=b"synthetic attachment"):
    return {"attachment_id": str(uuid4()), "filename": "generated file.pdf", "size": len(body),
            "sha256": hashlib.sha256(body).hexdigest(), "media_type": "application/octet-stream"}


class ConsumerTests(unittest.TestCase):
    def setUp(self):
        self.session, self.pid = str(uuid4()), str(uuid4())
        self.item = item()
        self.lock = threading.Lock()
        self.paste = Mock(return_value="paste_dispatched")
        self.consumer = receiver.AttachmentConsumer(self.session, self.lock, paste=self.paste, clock=lambda: 100)
        self.prepared = {"preparation_id": self.pid, "attachment": self.item,
                         "path": Path("/generated/attachment.pdf"), "png": None}
        self.action = {"action_id": str(uuid4()), "session_id": self.session, "preparation_id": self.pid,
                       "attachment": self.item, "remaining_ms": 5000}

    def test_paste_occurs_only_for_fresh_matching_action_and_is_never_repeated(self):
        self.paste.side_effect = lambda *_: "paste_dispatched" if self.lock.locked() else "paste_failed"
        result = self.consumer.consume(self.action, 100, self.prepared, lambda: False)
        self.assertEqual(result, ("executed", None))
        self.assertEqual(self.consumer.consume(self.action, 0, None, lambda: True), result)
        self.paste.assert_called_once()
        self.assertFalse(self.lock.locked())
        self.assertIn("--paste-attachment", self.paste.call_args.args[0])

    def test_mismatched_cache_stopped_and_expired_actions_cannot_paste(self):
        for prepared, started, stopped in [(None, 100, False), (self.prepared, 94, False),
                                           (self.prepared, 100, True)]:
            action = {**self.action, "action_id": str(uuid4())}
            result = self.consumer.consume(action, started, prepared, lambda: stopped)
            self.assertEqual(result[0], "cancelled")
        self.paste.assert_not_called()

    def test_shared_lock_consumes_budget_and_cannot_get_a_new_deadline(self):
        self.lock.acquire()
        try:
            result = self.consumer.consume(self.action, 94, self.prepared, lambda: False)
        finally:
            self.lock.release()
        self.assertEqual(result, ("cancelled", "expired"))
        self.assertEqual(self.consumer.consume(self.action, 100, self.prepared, lambda: False), result)
        self.paste.assert_not_called()

    def test_native_unconfirmed_result_does_not_report_dispatch_success(self):
        self.paste.return_value = "paste_unconfirmed"
        self.assertEqual(self.consumer.consume(self.action, 100, self.prepared, lambda: False),
                         ("cancelled", "paste_unconfirmed"))


class CacheTests(unittest.TestCase):
    def test_preparation_downloads_and_verifies_without_pasting_or_clipboard(self):
        body = b"generated bytes"
        meta = item(body)
        api = Mock()
        api.download.side_effect = lambda room, value, output, stopped: output.write(body)
        with tempfile.TemporaryDirectory() as tmp, patch.object(receiver, "run_native", return_value="file_ready") as native:
            cache = receiver.AttachmentCache(api, "generated-room", Path(tmp).resolve() / "cache")
            result = cache.prepare({"preparation_id": str(uuid4()), "attachment": meta}, lambda: False)
            self.assertEqual(result["path"].read_bytes(), body)
            self.assertIsNone(result["png"])
            self.assertEqual(native.call_args.args[0][1], "--prepare-attachment")
            again = cache.prepare({"preparation_id": str(uuid4()), "attachment": meta}, lambda: False)
            self.assertEqual(again["path"], result["path"])
            api.download.assert_called_once()

    def test_cache_symlink_and_altered_existing_bytes_are_rejected(self):
        meta = item()
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp).resolve()
            target = base / "target"; target.mkdir()
            alias = base / "alias"; alias.symlink_to(target, target_is_directory=True)
            with self.assertRaises(receiver.AttachmentError):
                receiver.private_directory(alias)
            cache = receiver.AttachmentCache(Mock(), "room", base / "cache")
            folder = receiver.private_directory(cache.root / meta["attachment_id"])
            (folder / meta["filename"]).write_bytes(b"changed")
            with patch.object(receiver, "run_native") as native, self.assertRaises(receiver.AttachmentError):
                cache.prepare({"preparation_id": str(uuid4()), "attachment": meta}, lambda: False)
            native.assert_not_called()

    def test_untrusted_remote_names_and_sizes_are_rejected(self):
        for changes in [{"filename": "../secret"}, {"filename": ".hidden"}, {"filename": "bad\\name"},
                        {"filename": "bad\nname"}, {"size": True}, {"size": receiver.MAX_FILE_BYTES + 1},
                        {"sha256": "x" * 64}, {"attachment_id": "../anything"}]:
            with self.subTest(changes=changes), self.assertRaises(receiver.AttachmentError):
                receiver.metadata({**item(), **changes})

    def test_download_rejects_changed_hash_and_excess_bytes(self):
        api = receiver.AttachmentApi("http://127.0.0.1")
        for body in [b"wrong body", b"x" * 100]:
            response = Mock()
            response.headers = {"Content-Length": str(len(b"generated"))}
            response.read1.side_effect = [body, b""]
            response.__enter__ = Mock(return_value=response)
            response.__exit__ = Mock(return_value=None)
            api.http = Mock()
            api.http.open.return_value = response
            with self.assertRaises(receiver.AttachmentError):
                api.download("room", item(b"generated"), io.BytesIO(), lambda: False)

    def test_dripping_transport_observes_stop_between_packets(self):
        started, stopped = threading.Event(), threading.Event()

        class Handler(BaseHTTPRequestHandler):
            def do_GET(inner):
                inner.send_response(200)
                inner.send_header("Content-Length", "8")
                inner.end_headers()
                for _ in range(8):
                    try:
                        inner.wfile.write(b"x"); inner.wfile.flush(); started.set()
                    except OSError:
                        break
                    if stopped.wait(0.25):
                        break
            def log_message(self, *_):
                pass

        httpd = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        thread = threading.Thread(target=httpd.serve_forever, daemon=True); thread.start()
        api = receiver.AttachmentApi("http://127.0.0.1:" + str(httpd.server_port))
        outcome = []
        def download():
            try:
                api.download("room", item(b"x" * 8), io.BytesIO(), stopped.is_set)
            except receiver.AttachmentError as error:
                outcome.append(error.code)
        job = threading.Thread(target=download, daemon=True)
        try:
            job.start(); self.assertTrue(started.wait(2))
            stopped.set(); job.join(timeout=1.5)
            self.assertFalse(job.is_alive())
            self.assertIn("receiver_stopped", outcome)
        finally:
            stopped.set(); httpd.shutdown(); httpd.server_close(); thread.join(2)

    def test_passive_disk_job_cannot_hold_actor_close_or_publish_late_ready(self):
        entered, release, stopped = threading.Event(), threading.Event(), threading.Event()
        prep = {"preparation_id": str(uuid4()), "attachment": item(), "ready": False}
        api, cache = Mock(), Mock()
        api.request.return_value = {"ok": True, "preparation": prep, "action": None}
        def blocked(*_):
            entered.set(); release.wait(3)
            return {"preparation_id": prep["preparation_id"], "attachment": prep["attachment"]}
        cache.prepare.side_effect = blocked
        actor = receiver.AttachmentActor("http://127.0.0.1", {
            "room_id": "room", "session_id": str(uuid4()), "receiver_token": "generated-token"},
            threading.Lock(), stopped.is_set, api=api, cache=cache)
        try:
            actor.start(); self.assertTrue(entered.wait(2)); started = time.monotonic()
            actor.close()
            self.assertLess(time.monotonic() - started, 1.5)
            release.set(); time.sleep(0.05)
            self.assertFalse(any(call.args[0] in {"prepared", "ack"} for call in api.request.call_args_list))
        finally:
            release.set(); stopped.set(); actor.close()


class AttachmentWireTests(unittest.TestCase):
    def test_real_http_upload_download_prepare_action_receipt_without_desktop_events(self):
        import test_attachments as backend
        fixture = backend.AttachmentApiTests("runTest")
        fixture.setUp()
        stopped, lock = threading.Event(), threading.Lock()
        body = b"generated attachment wire bytes"
        registration = fixture.httpd.signal_store.register("room")
        identity = {"room_id": "room", "session_id": registration["session_id"],
                    "receiver_token": registration["receiver_token"]}
        base = "http://127.0.0.1:" + str(fixture.httpd.server_port) + "/doubao"
        api = receiver.AttachmentApi(base)

        def wait_for(condition):
            deadline = time.monotonic() + 5
            while time.monotonic() < deadline:
                fixture.httpd.signal_store.poll("room", identity["session_id"], identity["receiver_token"])
                value = condition()
                if value:
                    return value
                time.sleep(0.05)
            self.fail("generated attachment wire timed out")

        actor = None
        try:
            with tempfile.TemporaryDirectory() as tmp, patch.object(receiver, "run_native", return_value="file_ready") as prepare_native:
                cache = receiver.AttachmentCache(api, "room", Path(tmp).resolve() / "cache")
                actor = receiver.AttachmentActor(base, identity, lock, stopped.is_set, api=api, cache=cache)
                actor.consumer.paste = Mock(side_effect=lambda *_: "paste_dispatched" if lock.locked() else "paste_failed")
                actor.start()
                wait_for(lambda: fixture.request("/api/attachments?room_id=room")[1]["receiver"]["ready"])
                code, uploaded, _ = fixture.upload(body)
                self.assertEqual(code, 200)
                meta, prep_id = uploaded["attachment"], str(uuid4())
                code, _, _ = fixture.request("/api/attachments/prepare", {
                    "room_id": "room", "session_id": identity["session_id"],
                    "preparation_id": prep_id, "attachment_id": meta["attachment_id"]})
                self.assertEqual(code, 200)
                wait_for(lambda: (fixture.request("/api/attachments?room_id=room")[1]["preparation"] or {}).get("ready"))
                self.assertEqual((cache.root / meta["attachment_id"] / meta["filename"]).read_bytes(), body)
                self.assertEqual(prepare_native.call_args.args[0][1], "--prepare-attachment")
                action_id = str(uuid4())
                code, _, _ = fixture.request("/api/attachments/action", {
                    "room_id": "room", "session_id": identity["session_id"],
                    "preparation_id": prep_id, "action_id": action_id})
                self.assertEqual(code, 200)
                wait_for(lambda: (fixture.request("/api/attachments?room_id=room&action_id=" + action_id)[1]["action"] or {}).get("status") == "executed")
                time.sleep(0.8)
                actor.consumer.paste.assert_called_once()
                self.assertEqual(actor.consumer.paste.call_args.args[0][1], "--paste-attachment")
                stopped.set(); actor.close()
        finally:
            stopped.set()
            if actor:
                actor.close()
            fixture.tearDown()


